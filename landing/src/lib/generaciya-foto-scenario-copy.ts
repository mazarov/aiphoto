export type GeneraciyaFotoScenarioFaq = {
  q: string;
  a: string;
};

export type GeneraciyaFotoScenarioContentBlock = {
  h2: string;
  paragraphs: string[];
};

export type GeneraciyaFotoScenarioCopy = {
  slug: GeneraciyaFotoScenarioSlug;
  label: string;
  metaTitle: string;
  metaDescription: string;
  h1: string;
  intro: string;
  examplesTitle: string;
  examplesIntro: string;
  promptCatalogHref: string;
  promptCatalogLabel: string;
  howToTitle: string;
  howToSteps: readonly string[];
  faq: readonly GeneraciyaFotoScenarioFaq[];
  contentBlocks: readonly GeneraciyaFotoScenarioContentBlock[];
};

export function getGeneraciyaFotoScenarioStarterPrompt(
  copy: GeneraciyaFotoScenarioCopy
): string {
  const action = copy.h1.replace(/^Сделать(?=\s)/, "Создай");
  const details = copy.howToSteps[1]
    .replace(/^Опишите(?=\s)/, "Опиши")
    .replace(/^Укажите(?=\s)/, "Укажи")
    .replace(/^Уточните(?=\s)/, "Уточни")
    .replace(/^Выберите(?=\s)/, "Выбери")
    .replace(/^Добавьте(?=\s)/, "Добавь");
  return `${action}. ${details}`;
}

type ProgrammaticScenarioInput = {
  metaTitleBase: string;
  h1Base: string;
  introLead: string;
  examplesTitle: string;
  subject: string;
  promptDetails: string;
  formatAdvice: string;
  promptCatalogHref: string;
  promptCatalogLabel: string;
};

function scenarioIntro(introLead: string): string {
  return `Выберите готовый образ ${introLead} или опишите кадр текстом — загрузите фото и получите реалистичный результат без студии.`;
}

function scenarioHero(
  metaTitleBase: string,
  h1Base: string,
  introLead: string
): Pick<GeneraciyaFotoScenarioCopy, "metaTitle" | "metaDescription" | "h1" | "intro"> {
  return {
    metaTitle: `${metaTitleBase} | PromptShot`,
    metaDescription: `${h1Base} по промту или снимку. Выберите образ, загрузите фото — нейросеть PromptShot без фотографа.`,
    h1: h1Base,
    intro: scenarioIntro(introLead),
  };
}

function createProgrammaticScenarioCopy({
  metaTitleBase,
  h1Base,
  introLead,
  examplesTitle,
  subject,
  promptDetails,
  formatAdvice,
  promptCatalogHref,
  promptCatalogLabel,
}: ProgrammaticScenarioInput): Omit<
  GeneraciyaFotoScenarioCopy,
  "slug" | "label"
> {
  const intro = scenarioIntro(introLead);
  return {
    ...scenarioHero(metaTitleBase, h1Base, introLead),
    examplesTitle,
    examplesIntro: `Выберите подходящий пример ${subject}, нажмите «Повторить» и измените промт под свою задачу. Начальная выдача содержит только карточки этой темы.`,
    promptCatalogHref,
    promptCatalogLabel,
    howToTitle: `Как создать ${subject} с помощью ИИ`,
    howToSteps: [
      `Выберите готовый пример ${subject} или начните с собственного описания.`,
      `Уточните в промте ${promptDetails}.`,
      "При необходимости добавьте исходную фотографию как референс композиции или внешности.",
      `Выберите модель и формат изображения. ${formatAdvice}`,
    ],
    faq: [
      {
        q: `Можно ли создать ${subject} по своей фотографии?`,
        a: "Да. Добавьте чёткий исходный снимок и явно опишите, какие элементы нужно сохранить, а какие — изменить в новой сцене.",
      },
      {
        q: `Что указать в промте для ${subject}?`,
        a: `Укажите ${promptDetails}. Не смешивайте несколько противоречивых стилей в одном запросе.`,
      },
      {
        q: "Как выбрать формат изображения?",
        a: formatAdvice,
      },
    ],
    contentBlocks: [
      {
        h2: `Идеи и промты для ${subject}`,
        paragraphs: [
          intro,
          `Для более предсказуемого результата последовательно задайте ${promptDetails}. Начните с простой композиции, а дополнительные детали добавляйте после первого результата.`,
        ],
      },
    ],
  };
}

