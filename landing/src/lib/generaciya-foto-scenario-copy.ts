export const GENERACIYA_FOTO_SCENARIO_COPY: readonly GeneraciyaFotoScenarioCopy[] =
  GENERACIYA_FOTO_SCENARIO_ROUTES.map((route) => ({
    slug: route.slug,
    label: route.label,
    ...COPY_BY_SLUG[route.slug],
  }));

export function findGeneraciyaFotoScenarioCopy(
  slug: string
): GeneraciyaFotoScenarioCopy | null {
  return (
    GENERACIYA_FOTO_SCENARIO_COPY.find((scenario) => scenario.slug === slug) ??
    null
  );
}
